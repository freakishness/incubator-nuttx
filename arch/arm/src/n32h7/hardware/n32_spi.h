#define SPI_I2S_CFGR_CHLEN (1 << 8) /* CHLEN */
#define SPI_I2S_CFGR_DATLEN_SHIFT (6)
#define SPI_I2S_CFGR_DATLEN_MASK (0x3 << SPI_I2S_CFGR_DATLEN_SHIFT) /* DATLEN */
#define SPI_I2S_CFGR_I2SCFG_SHIFT (4)
