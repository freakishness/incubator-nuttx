/******** Bit definition for SPI_I2S_CFGR register  ********/
#define SPI_I2S_CFGR_PCMBYPASS (1 << 11) /* PCMBYPASS */
#define SPI_I2S_CFGR_CLKPOL (1 << 10) /* CLKPOL */
