/******** Bit definition for I2C_CTRL1 register  ********/
#define I2C_CTRL1_FTXIE (1 << 31) /* FTXIE */
#define I2C_CTRL1_FRXIE (1 << 30) /* FRXIE */
#define I2C_CTRL1_DFX_SHIFT (24)
#define I2C_CTRL1_DFX_MASK (0x3F << I2C_CTRL1_DFX_SHIFT) /* DFX */
#define I2C_CTRL1_CRCEN (1 << 23) /* CRCEN */
#define I2C_CTRL1_ALRTEN (1 << 22) /* ALRTEN */
#define I2C_CTRL1_SMBD (1 << 21) /* SMBD */
#define I2C_CTRL1_SMBH (1 << 20) /* SMBH */
#define I2C_CTRL1_GENC (1 << 19) /* GENC */
#define I2C_CTRL1_NOSTRCH (1 << 17) /* NOSTRCH */
#define I2C_CTRL1_SBCTL (1 << 16) /* SBCTL */
#define I2C_CTRL1_DMARDEN (1 << 15) /* DMARDEN */
#define I2C_CTRL1_DMAWREN (1 << 14) /* DMAWREN */
#define I2C_CTRL1_AFOFF (1 << 12) /* AFOFF */
#define I2C_CTRL1_DF_SHIFT (8)
#define I2C_CTRL1_DF_MASK (0xF << I2C_CTRL1_DF_SHIFT) /* DF */
#define I2C_CTRL1_ERRIE (1 << 7) /* ERRIE */
#define I2C_CTRL1_TFCIE (1 << 6) /* TFCIE */
#define I2C_CTRL1_STOPIE (1 << 5) /* STOPIE */
#define I2C_CTRL1_NAKIE (1 << 4) /* NAKIE */
#define I2C_CTRL1_ADRIE (1 << 3) /* ADRIE */
#define I2C_CTRL1_RDRIE (1 << 2) /* RDRIE */
#define I2C_CTRL1_WDRIE (1 << 1) /* WDRIE */
#define I2C_CTRL1_I2CEN (1 << 0) /* I2CEN */

/******** Bit definition for I2C_CTRL2 register  ********/
#define I2C_CTRL2_CRCBYTE (1 << 26) /* CRCBYTE */
#define I2C_CTRL2_AUTOSTOP (1 << 25) /* AUTOSTOP */
#define I2C_CTRL2_REFILL (1 << 24) /* REFILL */
#define I2C_CTRL2_BYTECNT_SHIFT (16)
#define I2C_CTRL2_BYTECNT_MASK (0xFF << I2C_CTRL2_BYTECNT_SHIFT) /* BYTECNT */
#define I2C_CTRL2_NAK (1 << 15) /* NAK */
#define I2C_CTRL2_STOP (1 << 14) /* STOP */
#define I2C_CTRL2_START (1 << 13) /* START */
#define I2C_CTRL2_HDR10 (1 << 12) /* HDR10 */
#define I2C_CTRL2_ADR10 (1 << 11) /* ADR10 */
#define I2C_CTRL2_RWN (1 << 10) /* RWN */
#define I2C_CTRL2_SADR_SHIFT (0)
#define I2C_CTRL2_SADR_MASK (0x3FF << I2C_CTRL2_SADR_SHIFT) /* SADR */

/******** Bit definition for I2C_ADR1 register  ********/
#define I2C_ADR1_AD1EN (1 << 15) /* AD1EN */
#define I2C_ADR1_AD1MODE (1 << 10) /* AD1MODE */
#define I2C_ADR1_AD1_SHIFT (0)
#define I2C_ADR1_AD1_MASK (0x3FF << I2C_ADR1_AD1_SHIFT) /* AD1 */

/******** Bit definition for I2C_ADR2 register  ********/
#define I2C_ADR2_AD2EN (1 << 15) /* AD2EN */
#define I2C_ADR2_AD2MSK_SHIFT (8)
